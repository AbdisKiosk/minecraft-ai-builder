package me.abdiskiosk.minecraftaibuilder.bridge.we6;

import java.io.BufferedReader;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.Set;
import java.util.TreeMap;
import java.util.TreeSet;
import java.util.function.IntPredicate;

import me.abdiskiosk.minecraftaibuilder.common.BlockNames;
import me.abdiskiosk.minecraftaibuilder.common.BlockState;

/**
 * Modern block states to 1.8-1.12 {@code id:data} and back, loaded from {@code legacy-blocks.txt}
 * (generated by {@code tools/gen_legacy_blocks.py}). Pure Java so it can be unit tested without a server.
 */
final class LegacyBlockTable {

    /** Properties that select which part of a block a state is; matched before everything else. */
    private static final Set<String> STRUCTURAL = Set.of("half", "part", "type");
    /** Valid modern properties that 1.8 cannot store (shape is derived from neighbours, connections too). */
    private static final Set<String> MODERN_ONLY = Set.of("waterlogged", "shape", "north", "south", "east", "west", "up",
            "down", "distance", "snowy", "hanging", "stage", "bottom", "berries", "bloom", "thickness", "tilt", "orientation");

    record Entry(int id, int data, String type, Map<String, String> props, boolean place, boolean read) {
    }

    private record Hint(String glob, List<String> alternatives) {
    }

    private final Map<String, List<Entry>> byType = new TreeMap<>();
    private final Map<Integer, Entry> byKey = new HashMap<>();
    private final Map<String, Map<String, String>> defaults = new HashMap<>();
    private final Map<String, String> aliases = new HashMap<>();
    private final List<Hint> hints = new ArrayList<>();
    private final Map<String, int[]> items = new HashMap<>();
    private final Map<Integer, String> itemNames = new HashMap<>();
    private final Map<String, Map<String, List<String>>> valuesCache = new HashMap<>();

    /** @param idAvailable whether the running server has this block id at all (1.9+ blocks do not exist on 1.8) */
    static LegacyBlockTable load(InputStream in, IntPredicate idAvailable) {
        LegacyBlockTable table = new LegacyBlockTable();
        try (BufferedReader reader = new BufferedReader(new InputStreamReader(in, StandardCharsets.UTF_8))) {
            String line;
            while ((line = reader.readLine()) != null) {
                if (line.isBlank() || line.startsWith("#")) continue;
                table.parse(line.trim(), idAvailable);
            }
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
        return table;
    }

    private void parse(String line, IntPredicate idAvailable) {
        String[] f = line.split(" ", 4);
        if (line.startsWith("@alias ")) {
            aliases.put(f[1], f[2]);
        } else if (line.startsWith("@hint ")) {
            hints.add(new Hint(f[1], List.of(f[2].split(","))));
        } else if (line.startsWith("=")) {
            defaults.put(f[0].substring(1), props(f.length > 1 ? f[1] : ""));
        } else if (line.startsWith("item ")) {
            String[] key = f[1].split(":");
            int[] pair = {Integer.parseInt(key[0]), Integer.parseInt(key[1])};
            items.putIfAbsent(f[2], pair);
            itemNames.put(pair[0] << 4 | pair[1], f[2]);
        } else {
            boolean place = !line.startsWith("-");
            boolean read = !line.startsWith("+");
            String[] key = f[0].replaceFirst("^[+-]", "").split(":");
            int id = Integer.parseInt(key[0]);
            if (!idAvailable.test(id)) return;
            Entry e = new Entry(id, Integer.parseInt(key[1]), f[1], props(f.length > 2 ? f[2] : ""), place, read);
            byType.computeIfAbsent(e.type(), k -> new ArrayList<>()).add(e);
            if (read) byKey.putIfAbsent(e.id() << 4 | e.data(), e);
        }
    }

    private static Map<String, String> props(String text) {
        Map<String, String> out = new LinkedHashMap<>();
        if (text.isBlank()) return out;
        for (String pair : text.split(",")) {
            int eq = pair.indexOf('=');
            out.put(pair.substring(0, eq), pair.substring(eq + 1));
        }
        return out;
    }

    // ---- names ----

    String canonical(String type) {
        return aliases.getOrDefault(type, type);
    }

    boolean has(String type) {
        return byType.containsKey(canonical(type));
    }

    String defaultState(String type) {
        String canonical = canonical(type);
        return new BlockState(canonical,
                defaults.getOrDefault(canonical, Map.of())).toString();
    }

    Set<String> names() {
        return byType.keySet();
    }

    /** Property to values for the properties a state can actually vary in (two or more values). */
    Map<String, List<String>> properties(String type) {
        String t = canonical(type);
        return valuesCache.computeIfAbsent(t, k -> {
            Map<String, LinkedHashSet<String>> seen = new TreeMap<>();
            for (Entry e : byType.getOrDefault(k, List.of())) {
                e.props().forEach((p, v) -> seen.computeIfAbsent(p, x -> new LinkedHashSet<>()).add(v));
            }
            Map<String, List<String>> out = new LinkedHashMap<>();
            seen.forEach((p, v) -> {
                if (v.size() > 1) out.put(p, List.copyOf(v));
            });
            return out;
        });
    }

    /** Properties of the table that always have one value for this type (accepted, never an error). */
    Set<String> fixedProperties(String type) {
        Set<String> out = new TreeSet<>(MODERN_ONLY);
        Map<String, List<String>> varying = properties(type);
        for (Entry e : byType.getOrDefault(canonical(type), List.of())) {
            for (String p : e.props().keySet()) {
                if (!varying.containsKey(p)) out.add(p);
            }
        }
        return out;
    }

    // ---- modern state -> legacy ----

    /**
     * The legacy {@code [id, data]} that best matches the state. Unspecified properties take their modern
     * default (so {@code oak_stairs} means the same on 1.8 and 1.21); properties the legacy block cannot store are ignored.
     */
    Optional<int[]> toLegacy(String type, Map<String, String> given) {
        String t = canonical(type);
        Map<String, String> def = defaults.getOrDefault(t, Map.of());
        Entry best = null;
        long bestScore = Long.MAX_VALUE;
        for (Entry e : byType.getOrDefault(t, List.of())) {
            if (!e.place()) continue;
            long score = 0;
            for (Map.Entry<String, String> p : e.props().entrySet()) {
                String want = given.get(p.getKey());
                boolean explicit = want != null;
                if (!explicit) want = def.get(p.getKey());
                if (want == null || want.equals(p.getValue())) continue;
                score += STRUCTURAL.contains(p.getKey()) ? 1_000_000 : explicit ? 100 : 1;
            }
            if (score < bestScore) { // entries are sorted by id:data, so ties keep the lowest
                best = e;
                bestScore = score;
            }
        }
        return best == null ? Optional.empty() : Optional.of(new int[]{best.id(), best.data()});
    }

    /** Every {@code [id, data]} whose state is consistent with the given properties; for masks. */
    List<int[]> matching(String type, Map<String, String> given) {
        List<int[]> out = new ArrayList<>();
        Set<Integer> seen = new LinkedHashSet<>();
        for (Entry e : byType.getOrDefault(canonical(type), List.of())) {
            boolean ok = true;
            for (Map.Entry<String, String> g : given.entrySet()) {
                String have = e.props().get(g.getKey());
                if (have != null && !have.equals(g.getValue())) {
                    ok = false;
                    break;
                }
            }
            if (ok && seen.add(e.id() << 4 | e.data())) out.add(new int[]{e.id(), e.data()});
        }
        return out;
    }

    // ---- legacy -> modern state ----

    /** Modern state for a legacy block, with the properties that vary for that type; null if unknown. */
    String toModern(int id, int data) {
        Entry e = byKey.get(id << 4 | data);
        for (int mask : new int[]{7, 3, 0}) { // data bits some blocks carry that the table does not distinguish
            if (e != null) break;
            e = byKey.get(id << 4 | (data & mask));
        }
        if (e == null) return null;
        Map<String, List<String>> varying = properties(e.type());
        StringBuilder sb = new StringBuilder(e.type());
        boolean first = true;
        for (Map.Entry<String, String> p : e.props().entrySet()) {
            if (!varying.containsKey(p.getKey())) continue;
            sb.append(first ? '[' : ',').append(p.getKey()).append('=').append(p.getValue());
            first = false;
        }
        return first ? sb.toString() : sb.append(']').toString();
    }

    // ---- items (containers) ----

    /** Legacy {@code [id, damage]} of a modern item name. */
    Optional<int[]> item(String name) {
        return Optional.ofNullable(items.get(canonical(name)));
    }

    // ---- suggestions ----

    List<String> suggest(String type, int max) {
        Set<String> out = new LinkedHashSet<>();
        for (Hint h : hints) {
            if (BlockNames.glob(h.glob(), type)) {
                for (String alt : h.alternatives()) {
                    if (has(alt)) out.add(alt);
                }
            }
        }
        out.addAll(BlockNames.closest(type, byType.keySet(), max));
        return out.stream().limit(max).toList();
    }

    List<String> search(String query, int max) {
        return BlockNames.search(query, byType.keySet(), max);
    }
}
